'use client';

import { useEffect, useState } from 'react';
import { getMediaProxyUrl } from '@/lib/mediaUrl';

const DEFAULT_TIMESTAMP_SECONDS = 1;

interface UseVideoPosterFrameOptions {
  /** Set to false to skip capture entirely (e.g. before the item is visible). */
  enabled?: boolean;
  /** Timestamp to seek to before capturing, in seconds. Clamped to the clip's duration. */
  timestampSeconds?: number;
  /**
   * Pre-generated poster CID produced by /api/ipfs/upload/poster at upload
   * time (issue #1481).  When provided, the hook resolves immediately to the
   * gateway URL for the poster and skips the expensive client-side canvas
   * decode entirely — no range requests, no CORS issues, shared cache hit
   * for every viewer of the same clip.
   *
   * Supply the CID only; the hook loads it through the `/api/media` proxy,
   * which validates the CID and applies the content denylist.
   */
  posterCid?: string | null;
}

/**
 * Resolves a poster CID through the app's own media proxy, which validates the
 * CID and enforces the moderation denylist before reaching a gateway.
 */
function posterCidToUrl(cid: string): string {
  return getMediaProxyUrl(cid);
}

/**
 * Returns a poster-image URL for a highlight video.
 *
 * Fast path (issue #1481): when `posterCid` is supplied the hook returns the
 * corresponding IPFS gateway URL synchronously on first render — zero extra
 * network requests and no per-viewer canvas decode.  The CID is generated by
 * the upload pipeline via POST /api/ipfs/upload/poster and stored alongside
 * the video CID so it is available before the gallery is ever rendered.
 *
 * Slow path (legacy fallback): when `posterCid` is absent or null the hook
 * falls back to the original client-side canvas extraction.  This loads the
 * video off-screen with `preload="metadata"`, seeks to a fixed timestamp, and
 * draws the resulting frame onto an offscreen canvas, returning it as a
 * `data:` URL.  The fallback is kept for clips that were uploaded before the
 * upload pipeline was migrated, and for environments where the poster
 * generation API is unavailable.
 *
 * Returns `null` while capture is pending, disabled, or if it fails for any
 * reason (a CORS-tainted canvas, a network error, an empty video) — callers
 * should treat `null` as "no poster available" and degrade gracefully
 * rather than surfacing a broken image.
 */
export function useVideoPosterFrame(
  videoUrl: string,
  {
    enabled = true,
    timestampSeconds = DEFAULT_TIMESTAMP_SECONDS,
    posterCid,
  }: UseVideoPosterFrameOptions = {},
): string | null {
  // Fast path: if a pre-generated poster CID is available, resolve it
  // immediately and skip client-side extraction entirely.
  const preGeneratedUrl =
    posterCid && enabled ? posterCidToUrl(posterCid) : null;

  const [posterUrl, setPosterUrl] = useState<string | null>(preGeneratedUrl);

  // Keep the fast-path URL in sync if posterCid changes after mount.
  useEffect(() => {
    if (preGeneratedUrl) {
      setPosterUrl(preGeneratedUrl);
    }
  }, [preGeneratedUrl]);

  // Slow path (legacy client-side extraction): only run when no pre-generated
  // CID is available.
  useEffect(() => {
    if (!enabled || !videoUrl || preGeneratedUrl) return;

    let cancelled = false;
    const video = document.createElement('video');
    video.crossOrigin = 'anonymous';
    video.preload = 'metadata';
    video.muted = true;
    video.playsInline = true;

    function capture() {
      try {
        const canvas = document.createElement('canvas');
        canvas.width = video.videoWidth;
        canvas.height = video.videoHeight;
        if (canvas.width === 0 || canvas.height === 0) return;

        const ctx = canvas.getContext('2d');
        if (!ctx) return;

        ctx.drawImage(video, 0, 0, canvas.width, canvas.height);
        const dataUrl = canvas.toDataURL('image/jpeg', 0.7);
        if (!cancelled) setPosterUrl(dataUrl);
      } catch {
        // Tainted canvas (CORS) or other capture failure — no poster,
        // callers fall back to their default (no image) rendering.
      }
    }

    function handleLoadedMetadata() {
      const duration = video.duration;
      const target =
        Number.isFinite(duration) && duration > 0
          ? Math.min(timestampSeconds, Math.max(duration - 0.1, 0))
          : 0;
      video.currentTime = target;
    }

    function handleSeeked() {
      capture();
    }

    video.addEventListener('loadedmetadata', handleLoadedMetadata);
    video.addEventListener('seeked', handleSeeked);
    video.src = videoUrl;

    return () => {
      cancelled = true;
      video.removeEventListener('loadedmetadata', handleLoadedMetadata);
      video.removeEventListener('seeked', handleSeeked);
      video.src = '';
    };
  }, [videoUrl, enabled, timestampSeconds]);

  return posterUrl;
}
