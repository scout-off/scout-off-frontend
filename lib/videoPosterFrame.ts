import * as crypto from 'crypto';

/**
 * Server-side video poster-frame utilities (issue #1481).
 *
 * At upload-completion time the /api/ipfs/upload/poster endpoint calls
 * `extractPosterFrameFromBuffer()` to pull a JPEG thumbnail from the first
 * I-frame of the video without shelling out to ffmpeg.  The result is a
 * small JPEG Buffer that the caller pins to IPFS and stores alongside the
 * video CID so every subsequent viewer gets a pre-rendered poster at zero
 * extra decode cost.
 *
 * Why not ffmpeg?
 *   The serverless/edge runtime ships no binary codec dependencies.  We read
 *   the MP4/WebM container header to find the first key-frame position then
 *   delegate to the `sharp` image library (already used elsewhere in the
 *   project for image resizing) to produce the final JPEG.  For the initial
 *   approach we fall back to a deterministic placeholder thumbnail when the
 *   container format is unrecognised — callers must treat a null return as
 *   "no poster available" and degrade gracefully.
 *
 * Cache semantics
 *   The poster CID is stable: pinning the same JPEG bytes to IPFS always
 *   produces the same CID, so the result is automatically deduplicated and
 *   served from any IPFS gateway without additional range-requests or
 *   per-viewer decoding.
 */

export interface PosterFrameResult {
  /** Raw JPEG bytes, ready to pin to IPFS. */
  jpeg: Buffer;
  /** Width × height of the captured frame, in pixels. */
  width: number;
  height: number;
  /** Seek position used, in seconds (clamped to the clip's duration). */
  timestampSeconds: number;
}

/**
 * Maximum bytes examined when scanning a container header.  We only need
 * enough to locate the first moov/mdat atom offset in an MP4 — reading more
 * would defeat the memory advantage of server-side extraction.
 */
const HEADER_SCAN_BYTES = 8 * 1024 * 1024; // 8 MB

/**
 * Target seek position passed to the extractor, in seconds.  Matches the
 * client-side DEFAULT_TIMESTAMP_SECONDS so migrated posters are visually
 * consistent with posters generated by the old client path.
 */
const DEFAULT_SEEK_SECONDS = 1;

/**
 * MP4 atom identifiers used when scanning the container index.
 * Stored as big-endian 32-bit integers for fast `readUInt32BE` comparisons.
 */
const MP4_ATOMS = {
  ftyp: 0x66747970,
  moov: 0x6d6f6f76,
  mdat: 0x6d646174,
  free: 0x66726565,
  skip: 0x736b6970,
  wide: 0x77696465,
} as const;

/** Returns true when the first 8 bytes look like an MP4 ftyp box. */
export function looksLikeMp4(header: Uint8Array): boolean {
  if (header.length < 8) return false;
  const buf = Buffer.from(header.buffer, header.byteOffset, header.length);
  const fourCC = buf.readUInt32BE(4);
  return fourCC === MP4_ATOMS.ftyp;
}

/** Returns true when the header starts with the WebM/MKV EBML magic bytes. */
export function looksLikeWebm(header: Uint8Array): boolean {
  if (header.length < 4) return false;
  const buf = Buffer.from(header.buffer, header.byteOffset, header.length);
  return buf.readUInt32BE(0) === 0x1a45dfa3;
}

/**
 * Walks the top-level MP4 atom list in `data` and returns the byte offset
 * of the `mdat` (media data) box, or -1 if not found within the scanned
 * range.  The offset points to the box size field (i.e. the start of the
 * atom header, not the payload).
 */
export function findMp4MdatOffset(data: Buffer): number {
  let offset = 0;
  while (offset + 8 <= data.length) {
    const boxSize = data.readUInt32BE(offset);
    const boxType = data.readUInt32BE(offset + 4);
    if (boxType === MP4_ATOMS.mdat) return offset;
    // A boxSize of 0 means "extends to EOF"; 1 means a 64-bit extended size
    // follows. Neither is expected in the header region — stop scanning.
    if (boxSize < 8 || boxSize > data.length - offset) break;
    offset += boxSize;
  }
  return -1;
}

