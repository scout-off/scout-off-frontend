/** True when `frame` is the 1×1 placeholder rather than a real video frame. */
export function isPlaceholderFrame(frame: PosterFrameResult): boolean {
  return frame.width === 1 && frame.height === 1;
}

/**
 * Computes a stable cache key for a (videoCid, seekSeconds) pair so the
 * poster route can check whether a poster has already been generated without
 * hitting the database.
 */
export function posterCacheKey(videoCid: string, seekSeconds: number): string {
  return crypto
    .createHash('sha256')
    .update(`poster:${videoCid}:${seekSeconds.toFixed(3)}`)
    .digest('hex')
    .slice(0, 32);
}

/**
 * Attempts to extract a representative video frame by reading the container
 * header from `videoBytes` (the first `HEADER_SCAN_BYTES` of the file).
 *
 * In the current iteration this is a best-effort extraction that:
 *  1. Validates the container format (MP4 / WebM).
 *  2. Returns a deterministic placeholder JPEG for unrecognised formats.
 *
 * Full frame extraction requires either a WASM codec or a native binary
 * (ffmpeg).  This function returns the placeholder so the upload pipeline
 * always has *something* to pin, and the implementation note in
 * docs/video-poster-frames.md tracks the upgrade path to WASM-based
 * decoding.  See issue #1481 for context.
 *
 * The return value is never `null` — callers should store whatever is
 * returned and let viewers treat a 1×1 placeholder as "no poster".
 */
export function extractPosterFrameFromBuffer(
  videoBytes: Uint8Array,
  seekSeconds: number = DEFAULT_SEEK_SECONDS,
): PosterFrameResult {
  const buf = Buffer.from(
    videoBytes.buffer,
    videoBytes.byteOffset,
    Math.min(videoBytes.length, HEADER_SCAN_BYTES),
  );

  const isVideo = looksLikeMp4(videoBytes) || looksLikeWebm(videoBytes);
  if (!isVideo) {
    // Non-video or unrecognised container.
    return { jpeg: blackPixelJpeg(), width: 1, height: 1, timestampSeconds: 0 };
  }

  // For MP4s, confirm mdat atom is reachable within the scanned range.
  const mdatOffset = looksLikeMp4(videoBytes) ? findMp4MdatOffset(buf) : 0;
  const hasVideoData = mdatOffset >= 0;

  if (!hasVideoData) {
    // moov-after-mdat layout or progressive download not yet received;
    // return placeholder.
    return { jpeg: blackPixelJpeg(), width: 1, height: 1, timestampSeconds: 0 };
  }

  // TODO(#1481): replace placeholder with WASM-based frame extraction.
  // The WASM codec path is described in docs/video-poster-frames.md.
  // For now we return the placeholder and the upload pipeline stores it,
  // so at least the IPFS CID is pre-generated and shared across viewers.
  return {
    jpeg: blackPixelJpeg(),
    width: 1,
    height: 1,
    timestampSeconds: seekSeconds,
  };
}
