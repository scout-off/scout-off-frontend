/** True when `frame` is the 1×1 placeholder rather than a real video frame. */
export function isPlaceholderFrame(frame: PosterFrameResult): boolean {
  return frame.width === 1 && frame.height === 1;
}

/**
 * Computes a stable cache key for a (videoCid, seekSeconds) pair so the
 * poster route can check whether a poster has already been generated without
 * hitting the database.
 */
export function posterCacheKey(videoCid: string, seekSeconds: number): string {
  return crypto
    .createHash('sha256')
    .update(`poster:${videoCid}:${seekSeconds.toFixed(3)}`)
    .digest('hex')
    .slice(0, 32);
}

/**
 * Runs `ffmpeg` to extract a single frame at `seekSeconds` scaled so the long
 * edge is at most `maxEdge` pixels, returning the JPEG bytes.  Rejects when
 * the binary is missing, exits non-zero, or exceeds the wall-clock budget.
 */
function extractFrameWithFfmpeg(
  inputPath: string,
  seekSeconds: number,
  maxEdge: number,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const args = [
      '-hide_banner',
      '-loglevel', 'error',
      '-ss', seekSeconds.toFixed(3),
      '-i', inputPath,
      '-frames:v', '1',
      '-vf', `scale='min(${maxEdge},iw)':'min(${maxEdge},ih)':force_original_aspect_ratio=decrease`,
      '-q:v', '3',
      '-f', 'image2',
      '-vcodec', 'mjpeg',
      'pipe:1',
    ];
    const child = spawn('ffmpeg', args, { stdio: ['ignore', 'pipe', 'pipe'] });
    const chunks: Buffer[] = [];
    let stderr = '';
    const timer = setTimeout(() => {
      child.kill('SIGKILL');
      reject(new Error('ffmpeg extraction timed out'));
    }, EXTRACTION_TIMEOUT_MS);
    child.stdout.on('data', (c: Buffer) => chunks.push(c));
    child.stderr.on('data', (c: Buffer) => { stderr += c.toString(); });
    child.on('error', (err) => {
      clearTimeout(timer);
      reject(err);
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      if (code !== 0) {
        reject(new Error(`ffmpeg exited ${code}: ${stderr.slice(0, 200)}`));
        return;
      }
      const out = Buffer.concat(chunks);
      if (out.length === 0) {
        reject(new Error('ffmpeg produced no frame'));
        return;
      }
      resolve(out);
    });
  });
}

/**
 * Reads the JPEG SOF marker to recover the encoded frame dimensions.  Returns
 * null when the marker cannot be located.
 */
function readJpegDimensions(jpeg: Buffer): { width: number; height: number } | null {
  let i = 2;
  while (i + 9 < jpeg.length) {
    if (jpeg[i] !== 0xff) { i++; continue; }
    const marker = jpeg[i + 1];
    // SOF0..SOF15 excluding DHT(C4), JPG(C8), DAC(CC).
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
      return { height: jpeg.readUInt16BE(i + 5), width: jpeg.readUInt16BE(i + 7) };
    }
    const len = jpeg.readUInt16BE(i + 2);
    if (len < 2) return null;
    i += 2 + len;
  }
  return null;
}

/**
 * Attempts to extract a representative video frame from `videoBytes`.
 *
 * Strategy:
 *  1. Validate the container format (MP4 / WebM).
 *  2. Reject `moov`-after-`mdat` MP4s with a clear faststart error.
 *  3. Sample 2–3 timestamps around DEFAULT_SEEK_SECONDS and pick the frame
 *     with the highest luminance variance (skips black/white frames).
 *  4. Produce a poster (≤1280px) and a ≤320px thumbnail.
 *
 * Any failure (missing ffmpeg, timeout, decode error) degrades to the
 * placeholder with a structured warning so the upload still succeeds.
 */
export async function extractPosterFrameFromBuffer(
  videoBytes: Uint8Array,
  seekSeconds: number = DEFAULT_SEEK_SECONDS,
): Promise<PosterFrameResult> {
  const header = videoBytes.subarray(0, Math.min(videoBytes.length, HEADER_SCAN_BYTES));
  const isMp4 = looksLikeMp4(header);
  const isWebm = looksLikeWebm(header);

  if (!isMp4 && !isWebm) {
    console.warn(JSON.stringify({ event: 'poster.extract.unsupported', bytes: videoBytes.length }));
    return { jpeg: blackPixelJpeg(), width: 1, height: 1, timestampSeconds: seekSeconds };
  }

  if (isMp4 && isMoovAfterMdat(header)) {
    throw new Error('MP4 has moov after mdat; re-encode with faststart (-movflags +faststart)');
  }

  const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'poster-'));
  const inputPath = path.join(tmpDir, isMp4 ? 'input.mp4' : 'input.webm');
  try {
    await fs.writeFile(inputPath, videoBytes);

    const candidates = [seekSeconds, seekSeconds + 1, seekSeconds + 2];
    let best: { jpeg: Buffer; variance: number; ts: number } | null = null;
    for (const ts of candidates) {
      try {
        const jpeg = await extractFrameWithFfmpeg(inputPath, ts, POSTER_MAX_EDGE);
        // Approximate luminance variance via compressed byte entropy: a
        // fully black/white frame compresses to a tiny JPEG, so larger
        // payloads correlate with more visual detail.
        const variance = jpeg.length;
        if (!best || variance > best.variance) best = { jpeg, variance, ts };
      } catch (err) {
        console.warn(JSON.stringify({ event: 'poster.extract.frame_failed', ts, error: String(err) }));
      }
    }

    if (!best) {
      console.warn(JSON.stringify({ event: 'poster.extract.no_frames' }));
      return { jpeg: blackPixelJpeg(), width: 1, height: 1, timestampSeconds: seekSeconds };
    }

    const dims = readJpegDimensions(best.jpeg) ?? { width: 1, height: 1 };
    let thumbnail: Buffer | undefined;
    try {
      thumbnail = await extractFrameWithFfmpeg(inputPath, best.ts, THUMBNAIL_MAX_EDGE);
    } catch (err) {
      console.warn(JSON.stringify({ event: 'poster.extract.thumbnail_failed', error: String(err) }));
    }

    return {
      jpeg: best.jpeg,
      width: dims.width,
      height: dims.height,
      timestampSeconds: best.ts,
      thumbnail,
    };
  } catch (err) {
    console.warn(JSON.stringify({ event: 'poster.extract.failed', error: String(err) }));
    return { jpeg: blackPixelJpeg(), width: 1, height: 1, timestampSeconds: seekSeconds };
  } finally {
    await fs.rm(tmpDir, { recursive: true, force: true }).catch(() => undefined);
  }
}
